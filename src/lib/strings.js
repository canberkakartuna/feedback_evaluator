/**
 * Every word the interface says, in English and Turkish.
 *
 * One file rather than one per screen, because the thing that goes wrong with
 * translations is not writing them — it is noticing that one language has a key
 * the other does not. Side by side, a gap is visible; in two directories it is
 * not. `npm run check:strings` walks src/ and fails on a key that is used and
 * missing, or defined in one language only.
 *
 * **Interface, not content.** What a teacher types — activity titles, question
 * prompts, the AI prompt, rubric labels — is content and is never translated:
 * it is shown exactly as it was written, in whatever language it was written in.
 * The same goes for the tutor's replies and the marking summaries, which are
 * produced server-side against that authored content. A Turkish class working on
 * an activity a teacher wrote in Turkish sees Turkish throughout; the chrome
 * around it follows the language switch.
 *
 * Two conventions:
 *
 * - **`{name}` is a placeholder**, filled by the second argument to `t()`.
 *   Nothing else in a string is special.
 * - **`_one` / `_other`** are plural forms, chosen by `vars.count`. Turkish does
 *   not agree a noun with a numeral — "3 soru", not "3 sorular" — so both forms
 *   are usually the same sentence there. They are still both written out, so
 *   that reading down a key never leaves you wondering whether one was
 *   forgotten.
 *
 * Keys are nested for readability and flattened to `a.b.c` on load; see
 * ./i18n.jsx.
 */

